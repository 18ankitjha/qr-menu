import { useState, useCallback, useMemo } from 'react';
import { useAuth } from '../context/AuthContext';
import { FALLBACK_POLL_MS, RESTAURANT_EVENTS, restaurantRoom, useLiveRefresh } from '../realtime';
import { getBills, getBillPdfUrl, getErrorMessage } from '../services/api';
import { MESSAGES } from '../constants';
import type { IBill, BillStatus } from '../types';
import { BillBreakdown } from '../components/BillBreakdown';
import { formatMoney } from '../utils/money';
import './FormPage.css';
import './Orders.css';
import '../components/Billing.css';

// ============================================================
// Bills — history of table bills: list, view, open PDF (payment is taken in the table's bill popup)
// ============================================================

const PAGE = {
  TITLE: 'Bills',
  SUBTITLE: 'History of all bills. To take payment: Orders → "Orders & Bill" → Generate → Cash / UPI / Card.',
  NO_BILLS: 'No bills yet.',
  NO_RESTAURANT: 'Register a restaurant first.',
  FILTERS: [
    { value: '', label: 'All' },
    { value: 'UNPAID', label: 'Unpaid' },
    { value: 'PAID', label: 'Paid' },
  ] as { value: '' | BillStatus; label: string }[],
  UNPAID: 'Unpaid',
  PAID: 'Paid',
  VIEW: 'View',
  PDF: 'PDF',
  GENERATED_BY: 'Generated by',
  PAID_BY: 'Paid by',
  ORDERS: (n: number) => `${n} order${n !== 1 ? 's' : ''}`,
  CLOSE: 'Close',
  DATE_PRESETS: [
    { value: 'TODAY', label: 'Today' },
    { value: 'YESTERDAY', label: 'Yesterday' },
    { value: 'LAST_7', label: 'Last 7 days' },
    { value: 'ALL', label: 'All time' },
    { value: 'CUSTOM', label: 'Pick dates' },
  ] as { value: DatePreset; label: string }[],
  FROM: 'From',
  TO: 'To',
  NO_BILLS_IN_RANGE: 'No bills for these dates.',
  SUMMARY: (n: number) => `${n} bill${n !== 1 ? 's' : ''}`,
  SUMMARY_PAID: 'paid',
};

type DatePreset = 'TODAY' | 'YESTERDAY' | 'LAST_7' | 'ALL' | 'CUSTOM';

/** "2025-04-20" for a Date, in the browser's local time zone (what <input type="date"> uses). */
const toDateInput = (d: Date) =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

const startOfLocalDay = (d: Date) => new Date(d.getFullYear(), d.getMonth(), d.getDate());
const addDays = (d: Date, n: number) => new Date(d.getFullYear(), d.getMonth(), d.getDate() + n);
const parseDateInput = (v: string) => {
  const [y, m, d] = v.split('-').map(Number);
  return new Date(y, m - 1, d);
};

/** Local-day boundaries as ISO instants for the API (`to` is exclusive). */
const getDateRange = (preset: DatePreset, customFrom: string, customTo: string): { from?: string; to?: string } => {
  const today = startOfLocalDay(new Date());
  switch (preset) {
    case 'TODAY':
      return { from: today.toISOString(), to: addDays(today, 1).toISOString() };
    case 'YESTERDAY':
      return { from: addDays(today, -1).toISOString(), to: today.toISOString() };
    case 'LAST_7':
      return { from: addDays(today, -6).toISOString(), to: addDays(today, 1).toISOString() };
    case 'CUSTOM':
      return {
        ...(customFrom && { from: parseDateInput(customFrom).toISOString() }),
        ...(customTo && { to: addDays(parseDateInput(customTo), 1).toISOString() }),
      };
    default:
      return {};
  }
};

const BILL_PUSHES = [RESTAURANT_EVENTS.BILL_UPDATED] as const;

const Bills = () => {
  const { restaurant } = useAuth();
  const [bills, setBills] = useState<IBill[]>([]);
  const [statusFilter, setStatusFilter] = useState<'' | BillStatus>('');
  const [datePreset, setDatePreset] = useState<DatePreset>('TODAY');
  const [customFrom, setCustomFrom] = useState(() => toDateInput(new Date()));
  const [customTo, setCustomTo] = useState(() => toDateInput(new Date()));
  const [viewBill, setViewBill] = useState<IBill | null>(null);
  const [message, setMessage] = useState('');
  const [isError, setIsError] = useState(false);

  const fetchBills = useCallback(async () => {
    if (!restaurant) return;
    try {
      const { data } = await getBills(restaurant._id, {
        ...(statusFilter && { status: statusFilter }),
        ...getDateRange(datePreset, customFrom, customTo),
      });
      setBills(data.data);
      setMessage('');
      setIsError(false);
    } catch (err) {
      setIsError(true);
      setMessage(getErrorMessage(err, MESSAGES.ERROR_GENERIC));
    }
  }, [restaurant, statusFilter, datePreset, customFrom, customTo]);

  const summary = useMemo(() => {
    const total = bills.reduce((sum, b) => sum + b.totalAmount, 0);
    const paid = bills.filter((b) => b.status === 'PAID').reduce((sum, b) => sum + b.totalAmount, 0);
    return { total, paid };
  }, [bills]);

  useLiveRefresh(fetchBills, {
    room: restaurantRoom(restaurant?._id),
    events: BILL_PUSHES,
    fallbackMs: FALLBACK_POLL_MS.BILLS,
  });

  const openPdf = (billId: string) => window.open(getBillPdfUrl(billId), '_blank');

  if (!restaurant) {
    return (
      <div className="form-page">
        <div className="empty-state">
          <div className="empty-icon">🏪</div>
          <p className="empty-text">{PAGE.NO_RESTAURANT}</p>
        </div>
      </div>
    );
  }

  return (
    <div className="bills-page">
      <div className="page-header">
        <h1 className="page-title">{PAGE.TITLE}</h1>
        <p className="page-subtitle">{PAGE.SUBTITLE}</p>
      </div>

      {message && <div className={`form-message ${isError ? 'form-message--error' : ''}`}>{message}</div>}

      <div className="filter-bar bills-date-bar">
        {PAGE.DATE_PRESETS.map((p) => (
          <button
            key={p.value}
            className={`filter-chip ${datePreset === p.value ? 'filter-chip--active' : ''}`}
            onClick={() => setDatePreset(p.value)}
          >
            📅 {p.label}
          </button>
        ))}
        {datePreset === 'CUSTOM' && (
          <div className="bills-date-inputs">
            <label>
              {PAGE.FROM}
              <input
                type="date"
                className="form-input"
                value={customFrom}
                max={customTo || undefined}
                onChange={(e) => setCustomFrom(e.target.value)}
              />
            </label>
            <label>
              {PAGE.TO}
              <input
                type="date"
                className="form-input"
                value={customTo}
                min={customFrom || undefined}
                onChange={(e) => setCustomTo(e.target.value)}
              />
            </label>
          </div>
        )}
      </div>

      <div className="filter-bar">
        {PAGE.FILTERS.map((f) => (
          <button
            key={f.value}
            className={`filter-chip ${statusFilter === f.value ? 'filter-chip--active' : ''}`}
            onClick={() => setStatusFilter(f.value)}
          >
            {f.label}
          </button>
        ))}
      </div>

      {bills.length === 0 ? (
        <div className="empty-state">
          <div className="empty-icon">🧾</div>
          <p className="empty-text">{datePreset === 'ALL' ? PAGE.NO_BILLS : PAGE.NO_BILLS_IN_RANGE}</p>
        </div>
      ) : (
        <div className="bills-list">
          <div className="bills-summary">
            <span>{PAGE.SUMMARY(bills.length)}</span>
            <span>
              <strong>{formatMoney(summary.total)}</strong>
              {summary.paid !== summary.total && ` · ${formatMoney(summary.paid)} ${PAGE.SUMMARY_PAID}`}
            </span>
          </div>
          {bills.map((bill) => (
            <div key={bill._id} className="bill-card">
              <div className="bill-card-main">
                <span className="bill-card-number">
                  {bill.billNumber} · Table #{bill.tableNumber}{bill.tableLabel ? ` (${bill.tableLabel})` : ''}{' '}
                  <span className={`bill-chip ${bill.status === 'PAID' ? '' : 'bill-chip--unpaid'}`}>
                    {bill.status === 'PAID' ? `${PAGE.PAID} · ${bill.paymentMode}` : PAGE.UNPAID}
                  </span>
                </span>
                <span className="bill-card-meta">
                  {new Date(bill.createdAt).toLocaleString()} · {PAGE.ORDERS(bill.orderIds.length)} · {PAGE.GENERATED_BY} {bill.generatedBy}
                  {bill.paidBy ? ` · ${PAGE.PAID_BY} ${bill.paidBy}` : ''}
                </span>
              </div>
              <div className="bill-card-actions">
                <span className="bill-card-amount">{formatMoney(bill.totalAmount)}</span>
                <button className="btn-secondary btn-sm" onClick={() => setViewBill(bill)}>{PAGE.VIEW}</button>
                <button className="btn-secondary btn-sm" onClick={() => openPdf(bill._id)}>🧾 {PAGE.PDF}</button>
              </div>
            </div>
          ))}
        </div>
      )}

      {viewBill && (
        <div className="modal-overlay" onClick={() => setViewBill(null)}>
          <div className="modal-card" onClick={(e) => e.stopPropagation()}>
            <div className="bill-modal-header">
              <h2 className="card-title">{viewBill.billNumber} · Table #{viewBill.tableNumber}</h2>
              <button className="btn-icon" onClick={() => setViewBill(null)} title={PAGE.CLOSE}>✕</button>
            </div>
            <p className="bill-muted">{new Date(viewBill.createdAt).toLocaleString()}</p>
            <BillBreakdown totals={viewBill} />
            <div className="btn-row" style={{ marginTop: 16 }}>
              <button className="btn-secondary" onClick={() => openPdf(viewBill._id)}>🧾 {PAGE.PDF}</button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};

export { Bills };
